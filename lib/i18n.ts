export function formatDate(d: Date | string | null | undefined, l: Locale) {
  if (!d) return '';
  return new Intl.DateTimeFormat(l === 'ar' ? 'ar-JO' : 'en-GB', { day: 'numeric', month: 'long', year: 'numeric' }).format(new Date(d));
}
